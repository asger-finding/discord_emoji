// Scrapes Discord's emoji table from the web client and writes index.js, index.cjs and their typings.
// Run with `npm run scrape`.

import { writeFile } from 'node:fs/promises';

interface Emoji {
  names: string[];
  surrogates: string;
  diversity?: string[];
}

const ORIGIN = 'https://discord.com';
const MARKER = `JSON.parse('{"emojis":[`;
const SKIN_TONES = /[\u{1F3FB}-\u{1F3FF}]/u;

async function text(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`GET ${url} failed with ${response.status}`);
  return response.text();
}

async function assets(): Promise<string[]> {
  const html = await text(`${ORIGIN}/channels/@me`);
  const urls = new Set([...html.matchAll(/(?:src|href)="(\/assets\/[^"]+\.js)"/g)].map((m) => m[1]));
  // The emoji table sits in a chunk named like vnd-emoji.<hash>.js, so try those first.
  return [...urls].sort((a, b) => Number(b.includes('emoji')) - Number(a.includes('emoji')));
}

// Reads the single-quoted string literal that starts at `start` without evaluating any code.
function readStringLiteral(js: string, start: number): string {
  let end = start + 1;
  while (js[end] !== "'") {
    if (end >= js.length) throw new Error('Unterminated string literal');
    end += js[end] === '\\' ? 2 : 1;
  }
  const simple: Record<string, string> = { n: '\n', r: '\r', t: '\t', b: '\b', f: '\f', v: '\v', 0: '\0' };
  return js
    .slice(start + 1, end)
    .replace(/\\(u\{[\da-f]+\}|u[\da-f]{4}|x[\da-f]{2}|[\s\S])/gi, (_, escape: string) => {
      if (escape.startsWith('u{')) return String.fromCodePoint(parseInt(escape.slice(2, -1), 16));
      if (escape.startsWith('u') || escape.startsWith('x')) return String.fromCharCode(parseInt(escape.slice(1), 16));
      return simple[escape] ?? escape;
    });
}

async function scrape(): Promise<Emoji[]> {
  for (const asset of await assets()) {
    const js = await text(ORIGIN + asset);
    const at = js.indexOf(MARKER);
    if (at === -1) continue;
    console.info(`Found the emoji table in ${asset}`);
    const table = JSON.parse(readStringLiteral(js, at + 'JSON.parse('.length)) as { emojis: Emoji[] };
    return table.emojis;
  }
  throw new Error('No asset contains the emoji table');
}

const entries = (await scrape())
  .filter((emoji) => !emoji.diversity && !SKIN_TONES.test(emoji.surrogates))
  .map((emoji): [string, string] => [emoji.names[0], emoji.surrogates]);

const header = '// Generated by scripts/scrape.ts from the Discord web client. Do not edit.\n';
const body = entries.map(([name, symbol]) => `  ${JSON.stringify(name)}: ${JSON.stringify(symbol)},`).join('\n');
const types = entries.map(([name, symbol]) => `  readonly ${JSON.stringify(name)}: ${JSON.stringify(symbol)};`).join('\n');

await writeFile('index.js', `${header}\nexport default {\n${body}\n};\n`);
await writeFile('index.cjs', `${header}\nmodule.exports = {\n${body}\n};\n`);
await writeFile('index.d.ts', `${header}\ndeclare const emoji: {\n${types}\n};\n\nexport default emoji;\n`);
await writeFile('index.d.cts', `${header}\ndeclare const emoji: {\n${types}\n};\n\nexport = emoji;\n`);
console.info(`Wrote ${entries.length} emojis`);
